/*

matrix chain multiplication

矩阵链乘问题：

给定 n 个矩阵的链 <A1, A2, ..., An>，矩阵 Ai 的规模为 p[i-1] x p[i]，
求一组运算顺序，使得乘积 A1A2...An 所需的乘法次数最少。
矩阵乘法满足结合律，不同的加括号方式得到的结果相同，但乘法次数不同。

问题分析：

p x q 和 q x r 的两个矩阵相乘，需要 pqr 次乘法，结果规模为 p x r。
比如 1x2、2x3、3x4 的矩阵链乘，顺序相乘需要 1*2*3 + 1*3*4 = 18 次；
后两个先乘需要 2*3*4 + 1*2*4 = 32 次。

n 个矩阵链乘，加括号的方式共有第 n-1 个卡特兰数
C(n-1) = 1/n * C(2n-2, n-1) 种，随 n 指数增长，直接枚举不可行。

最优子结构：

无论哪种运算顺序，最后一步一定是把链 Ai..Aj 在某个位置 k（i <= k < j）
分成左右两部分 Ai..Ak 和 A(k+1)..Aj，先把两部分各自算好再相乘。
左、右两部分又各自是更短的矩阵链乘问题，即形成子问题。

递推式：

m[i][j] = 0,                                          i == j
m[i][j] = min( m[i][k] + m[k+1][j] + p[i-1]*p[k]*p[j] ),  i <= k < j

其中 m[i][j] 表示计算 Ai..Aj 的最少乘法次数，p[i-1]*p[k]*p[j] 是
最后一步把左右两部分结果相乘的代价（左结果规模 p[i-1] x p[k]，
右结果规模 p[k] x p[j]）。

若直接按递推式递归求解，子问题被大量重复计算（指数级）；采用
自底向上填表，按链的长度从小到大计算，每个 m[i][j] 只算一次，
总时间复杂度 O(n^3)，空间复杂度 O(n^2)。

*/

